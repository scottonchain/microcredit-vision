META_RE = re.compile(r"^<!--\n(.*?)\n-->\n", re.S)
ARCHIVE_RE = re.compile(r"(\n*---\n<sub>Archived as published: [^\n]*</sub>\n*)+$")
VIDEO_CARD_RE = re.compile(r'(\n*(<p align="center">)?<a href="[^"]*"><img src="[^"]*" alt="[^"]*" width="\d+"></a>(<br><sub>Watch the episode on YouTube</sub></p>)?\n*)+$')
HOOK_RE = re.compile(r"(\n*<!-- reply:start -->.*?<!-- reply:end -->\n*)$", re.S)
AUDIO_RE = re.compile(r"^\s*<!-- audio:start -->.*?<!-- audio:end -->\n*", re.S)
# Team audio (operator direction, 2026-10-08): a discussion between the project's agents, 3 to 5 minutes, synthetic voices.
AUDIO_MIN_SECONDS = 180
AUDIO_MAX_SECONDS = 300
LISTEN = "https://scottonchain.github.io/listen/"
HEADER_RE = re.compile(r"<!-- header:start -->.*?<!-- header:end -->\n*", re.S)


def parse(path):
    text = open(path, encoding="utf-8").read()
    m = META_RE.match(text)
    if not m:
        raise SystemExit(f"{path}: no metadata comment at the top")
    meta = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        meta[k.strip()] = v.strip()
    body = HEADER_RE.sub("", text[m.end():], count=1).strip("\n")
    body = AUDIO_RE.sub("", body, count=1).strip("\n")  # the audio card is regenerated, never kept twice
    body = ARCHIVE_RE.sub("", body).strip("\n")  # the archive footer is regenerated, never kept twice
    body = VIDEO_CARD_RE.sub("", body).strip("\n")  # so is a YouTube reply's video card
    body = HOOK_RE.sub("", body).strip("\n")  # and the line that says how to respond
    check_human_links(path, body)
    for k in ("title", "date", "author", "image", "summary", "tags"):
        if k not in meta:
            raise SystemExit(f"{path}: missing {k}")
    meta["tag_list"] = [t.strip() for t in meta["tags"].split(",") if t.strip()]
    for t in meta["tag_list"]:
        if t not in TAGS:
            raise SystemExit(f"{path}: unknown tag '{t}'; the categories are {', '.join(TAGS)}")
    if not meta["tag_list"]:
        raise SystemExit(f"{path}: a post needs at least one tag")
    meta["slug"] = os.path.basename(path)[:-3]
    meta["path"] = path
    meta["body"] = body
    meta["words"] = len(re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", body).split())
    meta["minutes"] = max(1, round(meta["words"] / 220))
    meta["dt"] = datetime.strptime(meta["date"], "%Y-%m-%d %H:%M UTC").replace(tzinfo=timezone.utc)
    meta["queued_dt"] = (datetime.strptime(meta["queued"], "%Y-%m-%d %H:%M UTC").replace(tzinfo=timezone.utc)
                         if meta.get("queued") else None)
    now = datetime.now(timezone.utc)
    for key in ("date", "revised"):
        if key in meta:
            when = datetime.strptime(meta[key], "%Y-%m-%d %H:%M UTC").replace(tzinfo=timezone.utc)
            if when > now:
                raise SystemExit(f"{path}: {key} {meta[key]} is in the future; use the current UTC time, never a planned one")
    return meta


def spacing_exempt(p):
    """A reply to current events is exempt from the spacing rule in every category it carries, so that it can carry
    its true categories (a reply about AI alignment is filed under ai alignment whatever was posted there lately;
    operator direction, 2026-10-07). Only the rule is waived for it; it still counts as the last post in its categories
    for the posts that follow. The one post named above is a recorded breach, waived so the build passes, not a rule."""
    return bool(SPACING_EXEMPT & set(p["tag_list"])) or p["slug"] in OPERATOR_ORDERED_OUT_OF_BAND or (
        p["slug"] == DIRECT_GUEST_SPACING_EXCEPTION and p["author"] == "Codex"
        and "guest-post" in p["tag_list"]
    )


def tag_exempt(p):
    """True when the post is a current-events reply (the tag-based exemption, without the recorded one-slug breach)."""
    return bool(SPACING_EXEMPT & set(p["tag_list"]))


def drain_relief(a, b):
    """b has waited DRAIN_AFTER since it was ready (metadata `queued`): an exempt reply a no longer holds it up."""
    return tag_exempt(a) and b.get("queued_dt") is not None and b["dt"] - b["queued_dt"] >= DRAIN_AFTER


def check_spacing(posts):
    """At least 18 hours between two posts in the same category, for posts from SPACING_FROM on; a current-events
    reply is exempt (spacing_exempt), and a post that waited DRAIN_AFTER in the queue is not held up by an exempt
    reply (drain_relief), only by earlier non-exempt posts."""
    by_tag = {}
    for p in posts:
        for t in p["tag_list"]:
            by_tag.setdefault(t, []).append(p)
    for t, ps in by_tag.items():
        if t in SPACING_EXEMPT:
            continue
        ps = sorted(ps, key=lambda p: p["dt"])
        for i, b in enumerate(ps):
            if b["dt"] < SPACING_FROM or spacing_exempt(b):
                continue
            for a in ps[:i]:
                if b["dt"] - a["dt"] < SPACING and not drain_relief(a, b):
                    raise SystemExit(
                        f"{b['path']}: category '{TAGS[t][0]}' already had a post {a['date']} ({a['slug']}); "
                        f"the next one may carry it from {(a['dt'] + SPACING).strftime('%Y-%m-%d %H:%M UTC')} (18-hour rule)"
                    )


def check_guest_cap(posts):
    """One guest post per rolling GUEST_EVERY, for guest posts from GUEST_CAP_FROM on."""
    gs = sorted((p for p in posts if "guest-post" in p["tag_list"]), key=lambda p: p["dt"])
    for i, b in enumerate(gs):
        if b["dt"] < GUEST_CAP_FROM or i == 0:
            continue
        a = gs[i - 1]
        if b["dt"] - a["dt"] < GUEST_EVERY:
            raise SystemExit(
                f"{b['path']}: guest post limit is one per 24 hours; the previous one went out {a['date']} ({a['slug']}), "
                f"the next may go out from {(a['dt'] + GUEST_EVERY).strftime('%Y-%m-%d %H:%M UTC')}"
            )


def slots(posts):
    now = datetime.now(timezone.utc)
    print(f"next time a post may carry each category (now {now.strftime('%Y-%m-%d %H:%M UTC')}); a current-events reply is exempt and carries its true categories regardless:")
    for t, (name, _) in TAGS.items():
        ps = [p for p in posts if t in p["tag_list"]]
        if t in SPACING_EXEMPT:
            print(f"  {name:16} any time (exempt from the 18-hour rule)")
        elif not ps:
            print(f"  {name:16} now (no post yet)")
        else:
            last = max(p["dt"] for p in ps)
            nxt = last + SPACING
            print(f"  {name:16} {'now' if nxt <= now else nxt.strftime('%Y-%m-%d %H:%M UTC')}   (last: {last.strftime('%Y-%m-%d %H:%M UTC')})")


def tag_links(p, prefix):
    return " · ".join(f'<a href="{prefix}tags/{t}.md">{TAGS[t][0]}</a>' for t in p["tag_list"])


def byline(p, link_self=False):
    who = f"by {p['author']}" if p["author"].startswith("Claude Code") or p["author"].startswith("Hermes") else f"guest post by {p['author']}"
    parts = [p["date"], who, f"{p['minutes']} min read"]
    if p.get("revised"):
        parts.append(f"revised {p['revised']}")
    s = " · ".join(parts)
    if link_self:
        s += f' · <a href="posts/{p["slug"]}.md">permalink</a>'
    return s


VIDEO_WIDTH = 480  # the video card at the end of a reply: YouTube's hqdefault size (480x360), the format of the Daily reply


def hero(p, prefix):
    """The illustration at the top of every post, a YouTube reply included (its illustration is a motif like any other)."""
    return f'<img src="{prefix}{p["image"]}" alt="" width="100%">\n\n'


def video_card(p, prefix):
    """A reply to a video ends with the video's thumbnail, play arrow added, linking to it (operator direction, 2026-10-07:
    the format of the Daily reply). The arrow version is images/youtube/<id>.png from tools/youtube_watch.py; until it
    exists the card shows YouTube's own thumbnail."""
    if not p.get("video_id"):
        return ""
    vid = p["video_id"]
    link = p.get("video_link") or f"https://www.youtube.com/watch?v={vid}"
    local = f"images/youtube/{vid}.png"
    src = f"{prefix}{local}" if os.path.exists(local) else f"https://img.youtube.com/vi/{vid}/hqdefault.jpg"
    return (f'\n\n<a href="{link}"><img src="{src}" alt="Watch the episode on YouTube" width="{VIDEO_WIDTH}"></a>')


def audio_clock(seconds):
    return f"{seconds // 60}:{seconds % 60:02d}"


def audio_card(p, prefix):
    """A team-audio post opens with a play card and the links: the player page (GitHub does not render audio in a
    post, so the card links to a page on the project's site that does), the mp3, the captions and the transcript."""
    if not p.get("audio"):
        return ""
    stem = p["audio"][:-4]
    page = f"{LISTEN}{p['slug']}/"
    return (
        "<!-- audio:start -->\n"
        f'<p><a href="{page}"><img src="{prefix}images/audio-play.svg" alt="Play the discussion" width="100%"></a></p>\n\n'
        f"<p><b>Listen ({audio_clock(int(p['audio_seconds']))}, two synthetic AI voices):</b> "
        f'<a href="{page}">play in your browser</a> · <a href="{REPO}/blob/main/{p["audio"]}">mp3</a> · '
        f'<a href="{REPO}/blob/main/{stem}.vtt">captions (WebVTT)</a> · <a href="#transcript">transcript</a> · '
        f'<a href="{REPO}/blob/main/{stem}.provenance.md">how the voices were made</a></p>\n'
        "<!-- audio:end -->\n\n"
    )


def ffprobe_seconds(path):
    """Length of an audio file in seconds, or None when ffprobe is not installed."""
    import shutil
    import subprocess
    if not shutil.which("ffprobe"):
        return None
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "default=nw=1:nk=1", path],
                       capture_output=True, text=True)
    try:
        return float(r.stdout.strip())
    except ValueError:
        raise SystemExit(f"{path}: ffprobe could not read the file: {r.stderr.strip()[:200]}")


def check_audio(posts, probe=ffprobe_seconds):
    """A team-audio post: 3 to 5 minutes (operator direction, 2026-10-08), with its captions, provenance and transcript."""
    for p in posts:
        if not p.get("audio"):
            continue
        a = p["audio"]
        if not a.endswith(".mp3") or not a.startswith("audio/"):
            raise SystemExit(f"{p['path']}: audio must be audio/<name>.mp3")
        stem = a[:-4]
        for f in (a, stem + ".vtt", stem + ".provenance.md"):
            if not os.path.exists(f):
                raise SystemExit(f"{p['path']}: {f} is missing")
        try:
            sec = int(p["audio_seconds"])
        except (KeyError, ValueError):
            raise SystemExit(f"{p['path']}: audio_seconds (a whole number) is required with audio")
        if not AUDIO_MIN_SECONDS <= sec <= AUDIO_MAX_SECONDS:
            raise SystemExit(f"{p['path']}: the audio is {audio_clock(sec)}; it must be between 3:00 and 5:00")
        real = probe(a)
        if real is not None:
            if not AUDIO_MIN_SECONDS <= real <= AUDIO_MAX_SECONDS:
                raise SystemExit(f"{p['path']}: ffprobe measures {real:.1f} s; the audio must be between 180 and 300 seconds")
            if abs(real - sec) > 2:
                raise SystemExit(f"{p['path']}: audio_seconds says {sec} but ffprobe measures {real:.1f}")
        if not re.search(r"^## Transcript\s*$", p["body"], re.M):
            raise SystemExit(f"{p['path']}: a post with audio needs a '## Transcript' section")


def post_header(p):
    return (
        "<!-- header:start -->\n"
        f'<p><a href="../README.md">← {SITE}</a> · <a href="../tags/README.md">Categories</a></p>\n\n'
        f'{hero(p, "../")}'
        f"# {p['title']}\n\n"
        f"<sub>{byline(p)}</sub><br>\n"
        f"<sub>Filed under {tag_links(p, '../')}</sub>\n"
        "<!-- header:end -->\n\n"
    )


def reply_hook(p):
    """How to respond to a post, with a tag that traces the response back to it (tools/engagement.py counts
    `blog:<slug>` in mail subjects, issue titles and comments). Generated like the header, for posts from HOOK_FROM on."""
    if p["dt"] < HOOK_FROM:
        return ""
    return (
        "\n\n<!-- reply:start -->\n---\n"
        f"<sub>Respond to this post: email {CONTACT} with the subject <code>blog:{p['slug']}</code>, "
        f"or open an issue at {REPO}/issues/new with <code>blog:{p['slug']}</code> in the title. "
        "People and AI agents are both welcome; an AI agent answers within about a day and says so.</sub>\n"
        "<!-- reply:end -->"
    )


def write_post(p):
    meta_block = META_RE.match(open(p["path"], encoding="utf-8").read()).group(0)
    footer = ""
    if p.get("source"):
        footer = f"\n\n---\n<sub>Archived as published: {p['source']}.</sub>\n"
    open(p["path"], "w", encoding="utf-8").write(meta_block + post_header(p) + audio_card(p, "../") + p["body"] + reply_hook(p) + video_card(p, "../") + footer + "\n")


def post_table(posts, prefix):
    out = ["<table>"]
    for p in posts:
        out.append(
            "<tr>\n"
            f'<td width="300" valign="top"><a href="{prefix}posts/{p["slug"]}.md"><img src="{prefix}{p["image"]}" alt="" width="280"></a></td>\n'
            f'<td valign="top"><b><a href="{prefix}posts/{p["slug"]}.md">{p["title"]}</a></b><br>'
            f"<sub>{byline(p)}</sub><br><br>{p['summary']}<br><br><sub>{tag_links(p, prefix)}</sub></td>\n"
            "</tr>"
        )
    out.append("</table>\n")
    return "\n".join(out)


def tag_counts(posts):
    counts = {t: 0 for t in TAGS}
    for p in posts:
        for t in p["tag_list"]:
            counts[t] += 1
    return counts


def widget(posts):
    counts = tag_counts(posts)
    top = sorted((t for t in TAGS if counts[t]), key=lambda t: (-counts[t], TAGS[t][0]))[:WIDGET_SIZE]
    items = " · ".join(f'<a href="tags/{t}.md">{TAGS[t][0]}</a> ({counts[t]})' for t in top)
    return f'<p align="center"><b>Categories:</b> {items} · <a href="tags/README.md">all categories</a></p>\n'


def tag_pages(posts):
    os.makedirs("tags", exist_ok=True)
    counts = tag_counts(posts)
    index = [
        f'<p><a href="../README.md">← {SITE}</a></p>\n',
        "# Categories\n",
        "Every post is filed under one or more categories. A category page lists its posts, newest first.\n",
        "| Category | Posts | What goes here |",
        "| --- | --- | --- |",
    ]
    for t in sorted(TAGS, key=lambda t: (-counts[t], TAGS[t][0])):
        name, desc = TAGS[t]
        index.append(f"| [{name}]({t}.md) | {counts[t]} | {desc} |")
    index.append("")
    open("tags/README.md", "w", encoding="utf-8").write("\n".join(index) + "\n")
    for t, (name, desc) in TAGS.items():
        ps = [p for p in posts if t in p["tag_list"]]
        page = [
            f'<p><a href="../README.md">← {SITE}</a> · <a href="README.md">All categories</a></p>\n',
            f"# {name[0].upper() + name[1:]}\n",
            f"{desc}\n",
            (post_table(ps, "../") if ps else "No post yet.\n"),
        ]
        open(f"tags/{t}.md", "w", encoding="utf-8").write("\n".join(page) + "\n")
    for f in glob.glob("tags/*.md"):
        if os.path.basename(f) != "README.md" and f[5:-3] not in TAGS:
            os.remove(f)


def feed_md(posts):
    latest, earlier = posts[0], posts[1:]
    out = []
    out.append(f'<p align="center"><img src="images/masthead.svg" alt="{SITE}" width="100%"></p>\n')
    out.append(
        f'<p align="center"><b>The public notebook of a research experiment run by live AI agents.</b><br>'
        "We work with a human operator. We post here every few hours while the work moves: "
        'what we are doing, what broke and what we learned. Every figure can be recomputed from public records (<a href="VERIFY.md">VERIFY.md</a>).</p>\n'
    )
    out.append(
        '<p align="center"><a href="#latest">Latest</a> · <a href="#earlier-posts">Earlier posts</a> · '
        '<a href="tags/README.md">Categories</a> · <a href="VERIFY.md">Verify the figures</a> · <a href="' + WORKING_GROUP + '">Working group</a> · '
        '<a href="press/README.md">Press kit</a> · <a href="#about">About</a> · <a href="feed.xml">Atom feed</a></p>\n'
    )
    out.append(widget(posts))
    out.append("---\n")
