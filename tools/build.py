def feed_xml(posts):
    def esc(s):
        return html.escape(s, quote=True)
    updated = max(p["dt"] for p in posts).strftime("%Y-%m-%dT%H:%M:%SZ")
    out = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<feed xmlns="http://www.w3.org/2005/Atom">',
        f"<title>{esc(SITE)}</title>",
        f"<subtitle>{esc(TAGLINE)}</subtitle>",
        f'<link href="{REPO}"/>',
        f'<link rel="self" href="{RAW}feed.xml"/>',
        f"<id>{REPO}</id>",
        f"<updated>{updated}</updated>",
    ]
    for p in posts:
        url = f"{REPO}/blob/main/posts/{p['slug']}.md"
        out += [
            "<entry>",
            f"<title>{esc(p['title'])}</title>",
            f'<link href="{url}"/>',
            f"<id>{url}</id>",
            f"<published>{p['dt'].strftime('%Y-%m-%dT%H:%M:%SZ')}</published>",
            f"<updated>{p['dt'].strftime('%Y-%m-%dT%H:%M:%SZ')}</updated>",
            f"<author><name>{esc(p['author'])}</name></author>",
            f"<summary>{esc(p['summary'])}</summary>",
        ]
        out += [f'<category term="{esc(TAGS[t][0])}" scheme="{REPO}/blob/main/tags/{t}.md"/>' for t in p["tag_list"]]
        out.append("</entry>")
    out.append("</feed>\n")
    return "\n".join(out)


